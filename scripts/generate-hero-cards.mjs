import { mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cardsDirectory = join(projectRoot, "images", "Hero_Cards");
const outputFile = join(
  projectRoot,
  "src",
  "generated",
  "hero-card-images.js",
);
const supportedExtensions = new Set([".jpg", ".jpeg", ".png", ".webp"]);

const entries = await readdir(cardsDirectory, { withFileTypes: true });
const images = entries
  .filter(
    (entry) =>
      entry.isFile() &&
      supportedExtensions.has(extname(entry.name).toLowerCase()),
  )
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, "en", { numeric: true }));

if (images.length === 0) {
  throw new Error(`No supported hero cards found in ${cardsDirectory}`);
}

const publicPaths = images.map(
  (filename) => `/images/Hero_Cards/${encodeURIComponent(filename)}`,
);
const source = `// Generated by scripts/generate-hero-cards.mjs. Do not edit by hand.\nexport const heroCardImages = ${JSON.stringify(publicPaths, null, 2)};\n`;

await mkdir(dirname(outputFile), { recursive: true });
await writeFile(outputFile, source, "utf8");
console.log(`Generated ${publicPaths.length} hero card paths.`);
